import assert from 'node:assert/strict';
import { projectBinDumps } from '../src/lib/binDumpWorkflow.mjs';
const lot={id:'lot',lot_code:'LOT-A',bins_count:3,bins_dumped:0,net_weight:1000.1,remaining_weight:1000.1,dumped_weight:0,status:'recibido'};
const bins=['a','b','c'].map(id=>({id,bin_code:`BIN-${id}`,receipt_lot_id:'lot',net_weight:1000.1/3,status:'recibido',origin:'OP1NE'}));
const op=(id,binId,status='pending')=>({id,rpc:'dump_bin_by_qr',status,createdAt:'2026-09-30T18:50:00Z',params:{p_bin_id:binId,p_lot_id:'lot',p_dump_code:`VOL-${id}`}});
const operations=[op('1','a'),op('2','b'),op('3','c')];
let state=projectBinDumps([lot],bins,[],operations.slice(0,1));
assert.equal(state.lots[0].bins_dumped,1);
assert.equal(state.bins[0].status,'volcado');
assert.equal(state.bins[0].receipt_lot_id,'lot');
assert.equal(state.bins[0].origin,'OP1NE');
assert.equal(state.dumps[0].bin_id,'a');
assert.equal(state.dumps[0].pendingStatus,'pending');
state=projectBinDumps([lot],bins,[],operations);
assert.equal(state.lots[0].remaining_weight,0);
assert.ok(Math.abs(state.lots[0].dumped_weight-1000.1)<1e-9);
assert.equal(state.lots[0].status,'volcado');
assert.equal(state.dumps.length,3);
const replay=projectBinDumps(state.lots,state.bins,state.dumps,operations);
assert.equal(replay.dumps.length,3);
assert.equal(replay.lots[0].bins_dumped,3);
state=projectBinDumps([lot],bins,[],[op('1','a','conflict'),op('2','b')]);
assert.equal(state.lots[0].bins_dumped,0);
assert.equal(state.bins[0].pendingStatus,'conflict');
assert.equal(state.lots[0].pendingStatus,'conflict');
assert.equal(lot.bins_dumped,0);
assert.equal(bins[0].status,'recibido');
console.log('PASS: escaneo por BIN, saldo parcial/final exacto, historial preservado, reintentos y conflictos offline');
