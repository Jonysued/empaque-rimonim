import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import { enqueueCommand, listCommands, removeCommand,saveSnapshot,readSnapshot,migrateLegacyWorkspace } from '../src/lib/offlineStore.js';
const command=(id,resourceKey)=>({id,resourceKey,ownerId:'operator',createdAt:'2026-10-02T01:00:00Z'});
const duplicate=await Promise.allSettled([enqueueCommand(command('first','pallet:a')),enqueueCommand(command('second','pallet:a'))]);
assert.equal(duplicate.filter(r=>r.status==='fulfilled').length,1);
assert.equal((await listCommands('operator')).length,1);
await Promise.all([enqueueCommand(command('z','pallet:b')),enqueueCommand(command('a','pallet:c'))]);
assert.deepEqual((await listCommands('operator')).map(c=>c.id),['first','z','a']);
assert.equal((await listCommands('other-account')).length,0);
await removeCommand('first');
await enqueueCommand(command('new','pallet:a'));
assert.deepEqual((await listCommands('operator')).map(c=>c.id),['z','a','new']);
console.log('IndexedDB real: doble escaneo concurrente, orden de escaneos y separación de cuentas: OK');
await saveSnapshot('legacy-user','Pallet',[{id:'old-rimonim-pallet'}]);
await enqueueCommand({...command('legacy-command','pallet:legacy'),ownerId:'legacy-user'});
await migrateLegacyWorkspace('legacy-user',{id:'company-b',slug:'other'});
assert.equal((await listCommands('legacy-user')).length,1);
await migrateLegacyWorkspace('legacy-user',{id:'company-a',slug:'rimonim'});
assert.equal((await listCommands('legacy-user')).length,0);
assert.equal((await listCommands('legacy-user::company-a')).length,1);
assert.equal((await listCommands('legacy-user::company-b')).length,0);
assert.deepEqual(await readSnapshot('legacy-user::company-a','Pallet'),[{id:'old-rimonim-pallet'}]);
assert.equal(await readSnapshot('legacy-user::company-b','Pallet'),undefined);
await saveSnapshot('legacy-user::company-a','Pallet',[{id:'current-pallet'}]);
await migrateLegacyWorkspace('legacy-user',{id:'company-a',slug:'rimonim'});
assert.deepEqual(await readSnapshot('legacy-user::company-a','Pallet'),[{id:'current-pallet'}]);
console.log('PASS: migración offline conserva pendientes de Rimonim y separa caché y comandos por empresa');
